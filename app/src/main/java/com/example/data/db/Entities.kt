package com.example.data.db

import androidx.room.Entity
import androidx.room.ForeignKey
import androidx.room.Index
import androidx.room.PrimaryKey
import kotlinx.serialization.Serializable

@Entity(tableName = "chat_sessions")
data class ChatSessionEntity(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val title: String,
    val createdAt: Long = System.currentTimeMillis(),
    val updatedAt: Long = System.currentTimeMillis(),
)

@Serializable
data class SourceCitation(
    val knowledgeId: Long,
    val title: String,
    val sourceUrl: String,
    val similarity: Float,
    val confidence: Float,
)

@Entity(
    tableName = "chat_messages",
    foreignKeys = [
        ForeignKey(
            entity = ChatSessionEntity::class,
            parentColumns = ["id"],
            childColumns = ["sessionId"],
            onDelete = ForeignKey.CASCADE,
        ),
    ],
    indices = [Index("sessionId")],
)
data class ChatMessageEntity(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val sessionId: Long,
    val role: String, // "user" | "assistant" | "system"
    val content: String,
    val citationsJson: String = "[]",
    val createdAt: Long = System.currentTimeMillis(),
)

enum class SourceType {
    URL,
    TOPIC,
    SEARCH_QUERY,
}

enum class SourceStatus {
    IDLE,
    READING,
    SUCCESS,
    ERROR,
}

@Entity(tableName = "sources")
data class SourceEntity(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val type: String = SourceType.URL.name,
    val title: String,
    val value: String, // URL, topic name, or search query
    val enabled: Boolean = true,
    val lastReadAt: Long? = null,
    val entryCount: Int = 0,
    val lastError: String? = null,
    val status: String = SourceStatus.IDLE.name,
    val createdAt: Long = System.currentTimeMillis(),
)

@Entity(tableName = "knowledge_entries")
data class KnowledgeEntryEntity(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val title: String,
    val summary: String,
    val keyFacts: String,
    val sourceUrl: String,
    val sourceTitle: String,
    val confidence: Float = 0.8f,
    val embeddingJson: String = "[]",
    val createdAt: Long = System.currentTimeMillis(),
    val updatedAt: Long = System.currentTimeMillis(),
)

@Entity(tableName = "skills", indices = [Index(value = ["slug"], unique = true)])
data class SkillEntity(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val name: String,
    val slug: String,
    val description: String,
    val filePath: String,
    val currentVersion: Int = 1,
    val enabled: Boolean = true,
    val lastRunAt: Long? = null,
    val lastRunOutput: String? = null,
    val lastError: String? = null,
    val createdAt: Long = System.currentTimeMillis(),
    val updatedAt: Long = System.currentTimeMillis(),
)

@Entity(
    tableName = "skill_versions",
    foreignKeys = [
        ForeignKey(
            entity = SkillEntity::class,
            parentColumns = ["id"],
            childColumns = ["skillId"],
            onDelete = ForeignKey.CASCADE,
        ),
    ],
    indices = [Index("skillId")],
)
data class SkillVersionEntity(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val skillId: Long,
    val version: Int,
    val code: String,
    val changeReason: String,
    val isWorking: Boolean = true,
    val createdAt: Long = System.currentTimeMillis(),
)

@Entity(tableName = "eval_questions")
data class EvalQuestionEntity(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val question: String,
    val expectedAnswer: String,
    val isAutoGenerated: Boolean = false,
    val lastScore: Float? = null,
    val lastResponse: String? = null,
    val updatedAt: Long = System.currentTimeMillis(),
)

@Entity(tableName = "agent_logs")
data class AgentLogEntity(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val runId: String,
    val phase: String,
    val message: String,
    val level: String = "INFO", // INFO, SUCCESS, WARN, ERROR
    val timestamp: Long = System.currentTimeMillis(),
)

enum class ImprovementTargetType {
    SYSTEM_PROMPT,
    SKILL,
    RESEARCH_STRATEGY,
}

enum class ProposalStatus {
    PENDING,
    APPROVED,
    REJECTED,
    ROLLED_BACK,
}

@Entity(tableName = "improvement_proposals")
data class ImprovementProposalEntity(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val runId: String,
    val targetType: String,
    val targetId: String,
    val targetName: String,
    val reason: String,
    val beforeContent: String,
    val afterContent: String,
    val scoreBefore: Float,
    val scoreAfter: Float,
    val status: String = ProposalStatus.PENDING.name,
    val createdAt: Long = System.currentTimeMillis(),
)

@Entity(tableName = "github_prs")
data class GitHubPrEntity(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val taskDescription: String,
    val branchName: String,
    val prNumber: Int,
    val prUrl: String,
    val commitSha: String,
    val buildStatus: String = "queued",
    val buildConclusion: String? = null,
    val artifactUrl: String? = null,
    val runHtmlUrl: String? = null,
    val attempts: Int = 1,
    val lastError: String? = null,
    val createdAt: Long = System.currentTimeMillis(),
    val updatedAt: Long = System.currentTimeMillis(),
)

@Entity(
    tableName = "brain_transitions",
    indices = [Index(value = ["contextKey", "nextToken"], unique = true), Index(value = ["contextKey"])],
)
data class BrainTransitionEntity(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val contextKey: String,
    val nextToken: String,
    val weight: Float,
    val updatedAt: Long = System.currentTimeMillis(),
)

@Entity(tableName = "training_checkpoints")
data class TrainingCheckpointEntity(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val epoch: Int,
    val loss: Float,
    val perplexity: Float,
    val vocabSize: Int,
    val parameterCount: Int,
    val tokensProcessed: Int,
    val sourceLabel: String,
    val timestamp: Long = System.currentTimeMillis(),
)

